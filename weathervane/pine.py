"""Pine Script v6 generator: one `strategy()` per champion sleeve, with the exact semantics of DESIGN sections 5 and 6.

The generated script is the simulator written in Pine. The mapping, bar by bar (everything below runs on the close of
bar t and orders fill at the open of t+1, because `process_orders_on_close=false`):

* entry signal: builtin `ta.*` indicators, filters, direction gate, and `not (long and short)` on the same bar;
* stop = signal close -/+ stop_atr * ATR, target = signal close +/- target_atr * ATR, both placed with `strategy.exit`
  on the signal bar so they are active from the fill bar;
* trailing: highest high (lowest low) since the fill bar, minus (plus) trail_atr * ATR, only ever tightening the stop,
  re-issued on every bar close and effective on the next bar;
* time stop, exit signals and reversals are market orders at the next open (`strategy.close_all`, `strategy.entry`);
* one position, no pyramiding; quantity = equity * risk% / (stop distance * point value).
"""
from __future__ import annotations

import logging
import re
from datetime import datetime, timezone
from pathlib import Path

from . import config, spec
from .config import Instrument
from .live import live_sleeves

log = logging.getLogger("weathervane.pine")

INITIAL_CAPITAL = 100000
DO_NOT_EDIT = "GENERATED by Weathervane (weathervane/pine.py). Generated, do not edit. Regenerate with: python -m weathervane pine"


def pine_dir() -> Path:
    return config.path("pine")


def num(v: float) -> str:
    """A Pine numeric literal."""
    if isinstance(v, bool):
        raise TypeError("bool is not a number")
    if float(v) == int(v) and isinstance(v, int):
        return str(int(v))
    text = repr(round(float(v), 8))
    return text if any(c in text for c in ".e") else text + ".0"


def quote(s: str) -> str:
    return '"' + s.replace('"', "'") + '"'


class Inputs:
    """Collects `input.*` lines for one script and remembers each parameter's Pine variable name."""

    def __init__(self) -> None:
        self.lines: list[str] = []
        self.names: dict[str, str] = {}

    def add(self, path: str, var: str, value, param: spec.Param | None, title: str, group: str) -> str:
        if param is not None and param.kind == "choice":
            opts = ", ".join(quote(c) for c in param.choices)
            line = f"{var} = input.string({quote(value)}, {quote(title)}, options = [{opts}], group = {quote(group)})"
        elif param is not None and param.kind == "int":
            line = (f"{var} = input.int({num(int(value))}, {quote(title)}, minval = {num(int(param.low))}, "
                    f"maxval = {num(int(param.high))}, group = {quote(group)})")
        elif param is not None:
            line = (f"{var} = input.float({num(float(value))}, {quote(title)}, minval = {num(float(param.low))}, "
                    f"maxval = {num(float(param.high))}, step = 0.05, group = {quote(group)})")
        elif isinstance(value, bool):
            line = f"{var} = input.bool({'true' if value else 'false'}, {quote(title)}, group = {quote(group)})"
        else:
            raise ValueError(f"no input type for {path}")
        self.lines.append(line)
        self.names[path] = var
        return var


def entry_code(entry: dict, v: dict[str, str]) -> list[str]:
    """Pine lines that define longRaw and shortRaw for the entry type."""
    kind = entry["type"]
    p = lambda k: v[f"entry.{k}"]       # noqa: E731
    if kind == "donchian_breakout":
        return [f"longRaw = close > ta.highest(high, {p('len')})[1]", f"shortRaw = close < ta.lowest(low, {p('len')})[1]"]
    if kind == "ma_cross":
        return [f"maFast = f_ma({p('kind')}, close, {p('fast')})", f"maSlow = f_ma({p('kind')}, close, {p('slow')})",
                "longRaw = ta.crossover(maFast, maSlow)", "shortRaw = ta.crossunder(maFast, maSlow)"]
    if kind == "keltner_breakout":
        return [f"kcMid = ta.ema(close, {p('len')})", f"kcRange = {p('mult')} * ta.atr({p('len')})",
                "longRaw = ta.crossover(close, kcMid + kcRange)", "shortRaw = ta.crossunder(close, kcMid - kcRange)"]
    if kind == "momentum_roc":
        return [f"rocEntry = ta.roc(close, {p('len')})", f"longRaw = ta.crossover(rocEntry, {p('thr')})",
                f"shortRaw = ta.crossunder(rocEntry, -{p('thr')})"]
    if kind == "rsi_reversion":
        return [f"rsiEntry = ta.rsi(close, {p('len')})", f"longRaw = ta.crossover(rsiEntry, {p('lower')})",
                f"shortRaw = ta.crossunder(rsiEntry, {p('upper')})"]
    if kind == "bollinger_reversion":
        return [f"bbBasis = ta.sma(close, {p('len')})", f"bbDev = {p('mult')} * ta.stdev(close, {p('len')})",
                "longRaw = ta.crossover(close, bbBasis - bbDev)", "shortRaw = ta.crossunder(close, bbBasis + bbDev)"]
    raise ValueError(f"no Pine template for entry type {kind!r}")


def filter_code(k: int, flt: dict, v: dict[str, str]) -> list[str]:
    """Pine lines that define f<k>Long and f<k>Short for one filter."""
    kind, p = flt["type"], (lambda key: v[f"filters.{k}.{key}"])      # noqa: E731
    f = f"f{k}"
    if kind == "trend_ma":
        return [f"{f}Ma = f_ma({p('kind')}, close, {p('len')})", f"{f}Long = close > {f}Ma", f"{f}Short = close < {f}Ma"]
    if kind in ("adx_min", "adx_max"):
        cmp_ = f"{f}Adx >= {p('min')}" if kind == "adx_min" else f"{f}Adx <= {p('max')}"
        return [f"[{f}DiP, {f}DiM, {f}Adx] = ta.dmi({p('len')}, {p('len')})", f"{f}Long = {cmp_}", f"{f}Short = {f}Long"]
    if kind == "atr_rank":
        return [f"{f}Rank = ta.percentrank(ta.atr({p('len')}) / close, {p('lookback')})",
                f"{f}Long = {f}Rank >= {p('min')} and {f}Rank <= {p('max')}", f"{f}Short = {f}Long"]
    if kind == "roc_dir":
        return [f"{f}Roc = ta.roc(close, {p('len')})", f"{f}Long = {f}Roc > 0", f"{f}Short = {f}Roc < 0"]
    raise ValueError(f"no Pine template for filter type {kind!r}")


def exit_signal_code(sig: dict | None, v: dict[str, str]) -> list[str]:
    if sig is None:
        return ["xLong = false", "xShort = false"]
    if sig["type"] == "donchian_exit":
        n = v["exit.exit_signal.len"]
        return [f"xLong = close < ta.lowest(low, {n})[1]", f"xShort = close > ta.highest(high, {n})[1]"]
    return [f"xMa = f_ma({v['exit.exit_signal.kind']}, close, {v['exit.exit_signal.len']})", "xLong = close < xMa", "xShort = close > xMa"]


def describe(sleeve: dict) -> list[str]:
    e = sleeve["entry"]
    entry = f"{e['type']}(" + ", ".join(f"{k}={val}" for k, val in e.items() if k != "type") + ")"
    filt = ", ".join(f"{f['type']}(" + ", ".join(f"{k}={val}" for k, val in f.items() if k != "type") + ")" for f in sleeve["filters"])
    ex = sleeve["exit"]
    parts = [f"stop {ex['stop_atr']} ATR"]
    if ex.get("target_atr") is not None:
        parts.append(f"target {ex['target_atr']} ATR")
    if ex.get("trail_atr") is not None:
        parts.append(f"trail {ex['trail_atr']} ATR")
    if ex.get("time_stop_bars") is not None:
        parts.append(f"time stop {ex['time_stop_bars']} bars")
    if ex.get("exit_signal"):
        s = ex["exit_signal"]
        parts.append(f"{s['type']}(" + ", ".join(f"{k}={val}" for k, val in s.items() if k != "type") + ")")
    parts.append("reverse on opposite" if ex["reverse_on_opposite"] else "ignore opposite")
    return [f"Entry: {entry}", f"Filters: {filt or 'none'}", f"Exit: {', '.join(parts)}"]


def avg_commission_pct(instruments: list[Instrument]) -> float:
    """Half of the round-trip cost, as Pine percent commission per order, averaged over the sleeve's instruments."""
    if not instruments:
        return 0.0
    return sum(i.cost_bps for i in instruments) / len(instruments) / 2.0 / 100.0


def render(portfolio: str, champion_id: str, sleeve: dict, risk: float, universe: dict[str, Instrument], today: str) -> str:
    """The Pine v6 strategy source for one sleeve. `sleeve` has its live parameters applied."""
    sleeve = spec.normalise(sleeve)
    spec.validate_sleeve(sleeve)
    insts = [universe[i] for i in sleeve["instruments"] if i in universe]
    inp = Inputs()
    ex, e_table = sleeve["exit"], spec.ENTRY_TYPES[sleeve["entry"]["type"]]
    inp.add("direction", "i_direction", sleeve["direction"], spec.Param("choice", choices=spec.DIRECTIONS), "Direction", "Risk and direction")
    inp.add("risk", "i_risk", round(min(risk * 100.0, 5.0), 6), spec.Param("float", 0.01, 5.0), "Risk per trade (% of equity)", "Risk and direction")
    inp.add("atr_len", "i_atr_len", sleeve["atr_len"], spec.ATR_LEN, "ATR length (sizing, stops)", "Risk and direction")
    for key, par in e_table.items():
        inp.add(f"entry.{key}", f"i_entry_{key}", sleeve["entry"][key], par, f"Entry {key}", "Entry")
    for k, flt in enumerate(sleeve["filters"]):
        for key, par in spec.FILTER_TYPES[flt["type"]].items():
            inp.add(f"filters.{k}.{key}", f"i_f{k}_{key}", flt[key], par, f"Filter {k + 1} {flt['type']} {key}", "Filters")
    inp.add("exit.stop_atr", "i_stop_atr", ex["stop_atr"], spec.EXIT_PARAMS["stop_atr"], "Stop (ATR multiples)", "Exit")
    for key, var, title in (("target_atr", "i_target_atr", "Target (ATR multiples)"), ("trail_atr", "i_trail_atr", "Trailing stop (ATR multiples)"),
                            ("time_stop_bars", "i_time_stop", "Time stop (bars in trade)")):
        if ex.get(key) is not None:
            inp.add(f"exit.{key}", var, ex[key], spec.EXIT_PARAMS[key], title, "Exit")
    if ex.get("exit_signal"):
        for key, par in spec.EXIT_SIGNAL_TYPES[ex["exit_signal"]["type"]].items():
            inp.add(f"exit.exit_signal.{key}", f"i_xs_{key}", ex["exit_signal"][key], par, f"Exit signal {key}", "Exit")
    inp.add("exit.reverse_on_opposite", "i_reverse", bool(ex["reverse_on_opposite"]), None, "Reverse on opposite signal", "Exit")
    v = inp.names

    has_target, has_trail, has_time = ex.get("target_atr") is not None, ex.get("trail_atr") is not None, ex.get("time_stop_bars") is not None
    title = f"Weathervane {portfolio}/{sleeve['id']}"
    L: list[str] = ["//@version=6"]
    L += [f"// {DO_NOT_EDIT}", f"// Portfolio: {portfolio}   Sleeve: {sleeve['id']}   Champion: {champion_id}   Generated: {today}"]
    L += [f"// {line}" for line in describe(sleeve)]
    L += [f"// ATR length {sleeve['atr_len']}, direction {sleeve['direction']}. Daily bars only. Paper trading research, not advice.",
          "// Instruments and TradingView symbols (cost = round-trip estimate in bps, half is charged per order):"]
    L += [f"//   {i.id:<8} {i.tv:<18} {i.cost_bps:g} bps   {i.contract_note}" for i in insts]
    L += ["// Apply to one symbol on a 1D chart. Set Properties > Commission to that symbol's half cost if it differs from the default.", ""]
    L += [f"strategy({quote(title)}, shorttitle = {quote('WV ' + portfolio + '/' + sleeve['id'])}, overlay = true, "
          f"process_orders_on_close = false, calc_on_every_tick = false, pyramiding = 0, initial_capital = {INITIAL_CAPITAL},",
          f"     commission_type = strategy.commission.percent, commission_value = {num(avg_commission_pct(insts))}, "
          "default_qty_type = strategy.fixed, default_qty_value = 1,",
          "     margin_long = 0, margin_short = 0, fill_orders_on_standard_ohlc = true, max_bars_back = 1000)", ""]
    L += ["// ---- inputs (defaults are the champion's live parameters)"] + inp.lines + [""]
    L += ["f_ma(string kind, float src, int len) =>", "    float s = ta.sma(src, len)", "    float e = ta.ema(src, len)",
          '    kind == "sma" ? s : e', ""]
    L += ["// ---- entry signals on the close of bar t", "atrv = ta.atr(i_atr_len)"] + entry_code(sleeve["entry"], v)
    long_ok, short_ok = ["true"], ["true"]
    for k, flt in enumerate(sleeve["filters"]):
        L += filter_code(k, flt, v)
        long_ok.append(f"f{k}Long")
        short_ok.append(f"f{k}Short")
    L += [f"longSig = longRaw and {' and '.join(long_ok)} and i_direction != \"short\"",
          f"shortSig = shortRaw and {' and '.join(short_ok)} and i_direction != \"long\"",
          "validAtr = not na(atrv) and atrv > 0",
          "goLong = longSig and not shortSig and validAtr", "goShort = shortSig and not longSig and validAtr",
          "sig = goLong ? 1 : goShort ? -1 : 0", ""]
    L += ["// ---- exit signals (market exit at the next open)"] + exit_signal_code(ex.get("exit_signal"), v) + [""]
    L += ["// ---- position state after bar t's fills",
          "posSize = strategy.position_size", "inPos = posSize != 0.0", "side = posSize > 0 ? 1 : posSize < 0 ? -1 : 0",
          "barsHeld = inPos ? bar_index - strategy.opentrades.entry_bar_index(0) : 0",
          "var float stopLvl = na", "var float tgtLvl = na", "var float extreme = na", ""]
    L += ["// ---- extreme since the fill bar and trailing stop, updated on bar close, effective next bar",
          "if inPos",
          "    extreme := barsHeld == 0 ? (side > 0 ? high : low) : (side > 0 ? math.max(extreme, high) : math.min(extreme, low))"]
    if has_trail:
        L += ["    if not na(atrv)", f"        cand = extreme - side * {v['exit.trail_atr']} * atrv",
              "        stopLvl := side > 0 ? math.max(stopLvl, cand) : math.min(stopLvl, cand)"]
    L += [""]
    exit_terms = [f"barsHeld >= {v['exit.time_stop_bars']}"] if has_time else []
    exit_terms.append("(side > 0 ? xLong : xShort)")
    exit_expr = exit_terms[0] if len(exit_terms) == 1 else f"({' or '.join(exit_terms)})"
    L += ["// ---- orders", f"stopDist = {v['exit.stop_atr']} * atrv",
          "qty = stopDist > 0 ? (strategy.equity * i_risk / 100.0) / (stopDist * syminfo.pointvalue) : 0.0",
          f"exitNow = inPos and {exit_expr}",
          "isReverse = inPos and i_reverse and sig == -side", "isEntry = (isReverse or (not inPos and sig != 0)) and qty > 0"]
    tgt = f"close + sig * {v['exit.target_atr']} * atrv" if has_target else "na"
    L += ["if isEntry", "    stopLvl := close - sig * stopDist", f"    tgtLvl := {tgt}", "    if sig > 0",
          '        strategy.entry("L", strategy.long, qty = qty)', '        strategy.exit("XL", from_entry = "L", stop = stopLvl, limit = tgtLvl)',
          "    else", '        strategy.entry("S", strategy.short, qty = qty)',
          '        strategy.exit("XS", from_entry = "S", stop = stopLvl, limit = tgtLvl)',
          "else if exitNow", '    strategy.close_all(comment = "exit")', "else if inPos", "    if side > 0",
          '        strategy.exit("XL", from_entry = "L", stop = stopLvl, limit = tgtLvl)', "    else",
          '        strategy.exit("XS", from_entry = "S", stop = stopLvl, limit = tgtLvl)', ""]
    L += ["// ---- current stop and target of the open position", "showLevels = inPos and not isEntry",
          'plot(showLevels ? stopLvl : na, "Stop", color = color.red, style = plot.style_linebr)']
    if has_target:
        L += ['plot(showLevels ? tgtLvl : na, "Target", color = color.green, style = plot.style_linebr)']
    L += ['plotshape(isEntry and sig > 0, "Long signal", style = shape.triangleup, location = location.belowbar, color = color.green, size = size.tiny)',
          'plotshape(isEntry and sig < 0, "Short signal", style = shape.triangledown, location = location.abovebar, color = color.red, size = size.tiny)', ""]
    return "\n".join(L)


# ---- checks used by the tests and by `generate` ------------------------------------------------------------------------

def strip_strings_and_comments(text: str) -> str:
    out = []
    for line in text.splitlines():
        line = re.sub(r'"[^"]*"', '""', line)
        out.append(line.split("//")[0])
    return "\n".join(out)


def lint(text: str) -> list[str]:
    """Cheap structural checks. Returns a list of problems (empty when the text looks well formed)."""
    problems = []
    lines = text.splitlines()
    if not lines or lines[0].strip() != "//@version=6":
        problems.append("first line must be //@version=6")
    code = strip_strings_and_comments(text)
    for open_, close_ in ("()", "[]"):
        depth = 0
        for ch in code:
            depth += (ch == open_) - (ch == close_)
            if depth < 0:
                break
        if depth != 0:
            problems.append(f"unbalanced {open_}{close_}")
    if "\t" in text:
        problems.append("tab characters")
    if not re.search(r"^strategy\(", code, re.M):
        problems.append("missing strategy() call")
    if "generated, do not edit" not in text.lower():
        problems.append("missing generated header")
    defined = set(re.findall(r"^(i_\w+) = input\.", code, re.M))
    used = set(re.findall(r"\b(i_\w+)\b", code))
    if used - defined:
        problems.append(f"undefined inputs {sorted(used - defined)}")
    depth = 0
    for n, line in enumerate(code.splitlines(), 1):
        indent = len(line) - len(line.lstrip(" "))
        if line.strip() and depth == 0 and indent % 4:
            problems.append(f"line {n}: indent is not a multiple of 4")
        depth += line.count("(") - line.count(")") + line.count("[") - line.count("]")
    return problems


def generate(portfolio_ids: list[str], cfg: dict, today: str | None = None) -> list[Path]:
    """Write pine/<portfolio>_<sleeve>.pine for every champion sleeve and remove stale files of those portfolios."""
    universe, portfolios = config.load_universe(), config.load_portfolios()
    stamp = today or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    out_dir = pine_dir()
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for pid in portfolio_ids:
        champion = config.load_champion(pid)
        rules = config.load_rules(portfolios[pid].rules)
        risk = config.live_risk(champion, cfg, rules)
        keep = set()
        for sleeve in live_sleeves(champion):
            text = render(pid, champion["id"], sleeve, risk, universe, stamp)
            problems = lint(text)
            if problems:
                raise ValueError(f"generated Pine for {pid}/{sleeve['id']} failed checks: {problems}")
            path = out_dir / f"{pid}_{sleeve['id']}.pine"
            path.write_text(text + "\n", encoding="utf-8")
            keep.add(path.name)
            written.append(path)
        for old in out_dir.glob(f"{pid}_*.pine"):
            if old.name not in keep:
                old.unlink()
    log.info("wrote %d Pine scripts to %s", len(written), out_dir)
    return written
